"""QF_NRA export and conservative solver-model parsing.

The exported claim is intentionally bounded: independent periodic profiles and all
deterministic unilateral policies of the same period.  UNSAT never means that the
unrestricted quitting game lacks an equilibrium.
"""

from __future__ import annotations

import re
from collections.abc import Iterable, Iterator, Sequence
from dataclasses import dataclass
from fractions import Fraction
from itertools import product

from .quitting import Profile, QuittingGame, normalize_profile, periodic_regret_certificate
from .rational import Q


def _q(value: Q) -> str:
    if value.denominator == 1:
        return str(value.numerator)
    return f"(/ {value.numerator} {value.denominator})"


def _sum(terms: Iterable[str]) -> str:
    values = tuple(terms)
    if not values:
        return "0"
    if len(values) == 1:
        return values[0]
    return f"(+ {' '.join(values)})"


def _mul(terms: Iterable[str]) -> str:
    values = tuple(terms)
    if not values:
        return "1"
    if len(values) == 1:
        return values[0]
    return f"(* {' '.join(values)})"


def _outcome(variables: Sequence[str], mask: int) -> str:
    return _mul(
        variable if mask & (1 << player) else f"(- 1 {variable})"
        for player, variable in enumerate(variables)
    )


def _stage(game: QuittingGame, variables: Sequence[str], player: int) -> tuple[str, str]:
    survival = _outcome(variables, 0)
    reward = _sum(
        f"(* {_outcome(variables, mask)} {_q(game.payoffs[mask][player])})"
        for mask in range(1, 1 << game.players)
        if game.payoffs[mask][player] != 0
    )
    return survival, reward


def _value_system(
    game: QuittingGame,
    phase_variables: Sequence[Sequence[str]],
    player: int,
    value_prefix: str,
) -> tuple[list[str], list[str]]:
    period = len(phase_variables)
    names = [f"{value_prefix}_{phase}" for phase in range(period)]
    terms = [_stage(game, phase_variables[phase], player) for phase in range(period)]
    denominator = f"(- 1 {_mul(survival for survival, _ in terms)})"
    absorbing_equations = [
        f"(= {names[phase]} (+ {terms[phase][1]} "
        f"(* {terms[phase][0]} {names[(phase + 1) % period]})))"
        for phase in range(period)
    ]
    terminal_equations = [f"(= {name} {_q(game.continuation[player])})" for name in names]
    condition = (
        f"(or (and (> {denominator} 0) {' '.join(absorbing_equations)}) "
        f"(and (= {denominator} 0) {' '.join(terminal_equations)}))"
    )
    return names, [condition]


def export_periodic_qfnra(game: QuittingGame, period: int, epsilon: Q) -> str:
    if period < 1:
        raise ValueError("period must be positive")
    if epsilon < 0:
        raise ValueError("epsilon must be non-negative")
    lines = [
        "; generated by uniform-lab",
        "; SCOPE: independent profiles; all deterministic deviations with the same period",
        "; UNSAT excludes only this bounded strategy class, never arbitrary behavioral strategies",
        "(set-logic QF_NRA)",
        "(set-option :produce-models true)",
    ]
    variables = [
        [f"q_{phase}_{player}" for player in range(game.players)] for phase in range(period)
    ]
    for phase in range(period):
        for player in range(game.players):
            name = variables[phase][player]
            lines.extend(
                [f"(declare-fun {name} () Real)", f"(assert (and (<= 0 {name}) (<= {name} 1)))"]
            )
    profile_values: list[list[str]] = []
    for player in range(game.players):
        names, constraints = _value_system(game, variables, player, f"v_{player}")
        profile_values.append(names)
        lines.extend(f"(declare-fun {name} () Real)" for name in names)
        lines.extend(f"(assert {constraint})" for constraint in constraints)

    for player in range(game.players):
        for policy_number, policy in enumerate(product((0, 1), repeat=period)):
            deviating_variables = [list(phase) for phase in variables]
            for phase, action in enumerate(policy):
                deviating_variables[phase][player] = str(action)
            names, constraints = _value_system(
                game, deviating_variables, player, f"d_{player}_{policy_number}"
            )
            lines.extend(f"(declare-fun {name} () Real)" for name in names)
            lines.extend(f"(assert {constraint})" for constraint in constraints)
            for phase, name in enumerate(names):
                lines.append(
                    f"(assert (<= {name} (+ {profile_values[player][phase]} {_q(epsilon)})))"
                )
    lines.extend(["(check-sat)", "(get-model)"])
    return "\n".join(lines) + "\n"


Token = str | list["Token"]


def _tokens(text: str) -> Iterator[str]:
    clean = re.sub(r";[^\n]*", "", text)
    yield from re.findall(r"\(|\)|[^\s()]+", clean)


def _parse_one(tokens: Iterator[str], first: str | None = None) -> Token:
    token = next(tokens) if first is None else first
    if token != "(":
        return token
    output: list[Token] = []
    for token in tokens:
        if token == ")":
            return output
        output.append(_parse_one(tokens, token))
    raise ValueError("unterminated S-expression")


def parse_sexpressions(text: str) -> list[Token]:
    tokens = iter(_tokens(text))
    output: list[Token] = []
    while True:
        try:
            output.append(_parse_one(tokens))
        except StopIteration:
            return output


def _rational_atom(token: str) -> Q:
    cleaned = token[:-1] if token.endswith("?") else token
    if cleaned.endswith(".0"):
        cleaned = cleaned[:-2]
    return Fraction(cleaned)


def evaluate_rational(expression: Token) -> Q | None:
    if isinstance(expression, str):
        try:
            return _rational_atom(expression)
        except (ValueError, ZeroDivisionError):
            return None
    if not expression or not isinstance(expression[0], str):
        return None
    operator = expression[0]
    arguments = [evaluate_rational(argument) for argument in expression[1:]]
    if any(argument is None for argument in arguments):
        return None
    values = [argument for argument in arguments if argument is not None]
    if operator == "+":
        return sum(values, Fraction(0))
    if operator == "-" and len(values) == 1:
        return -values[0]
    if operator == "-" and len(values) == 2:
        return values[0] - values[1]
    if operator == "*":
        result = Fraction(1)
        for value in values:
            result *= value
        return result
    if operator == "/" and len(values) == 2 and values[1] != 0:
        return values[0] / values[1]
    return None


@dataclass(frozen=True)
class ParsedModel:
    status: str
    rationals: dict[str, Q]
    algebraic_or_unknown: dict[str, str]


def parse_solver_model(text: str) -> ParsedModel:
    stripped = text.lstrip()
    status = stripped.split(None, 1)[0] if stripped else "missing"
    rationals: dict[str, Q] = {}
    unknown: dict[str, str] = {}

    def definitions(expression: Token) -> Iterator[list[Token]]:
        if not isinstance(expression, list):
            return
        if expression and expression[0] == "define-fun":
            yield expression
            return
        for child in expression:
            yield from definitions(child)

    for expression in parse_sexpressions(text):
        for node in definitions(expression):
            if (
                len(node) >= 5
                and node[0] == "define-fun"
                and isinstance(node[1], str)
                and node[2] == []
            ):
                value = evaluate_rational(node[4])
                if value is None:
                    unknown[node[1]] = repr(node[4])
                else:
                    rationals[node[1]] = value
    return ParsedModel(status, rationals, unknown)


def profile_from_model(game: QuittingGame, period: int, model: ParsedModel) -> Profile:
    raw: list[list[Q]] = []
    for phase in range(period):
        row: list[Q] = []
        for player in range(game.players):
            name = f"q_{phase}_{player}"
            if name not in model.rationals:
                raise ValueError(f"model has no independently rational value for {name}")
            row.append(model.rationals[name])
        raw.append(row)
    return normalize_profile(game, raw)


def independently_check_model(
    game: QuittingGame, period: int, epsilon: Q, model_text: str
) -> tuple[ParsedModel, Profile, bool]:
    model = parse_solver_model(model_text)
    if model.status != "sat":
        raise ValueError(f"solver status is {model.status!r}, not 'sat'")
    profile = profile_from_model(game, period, model)
    certificate = periodic_regret_certificate(game, profile)
    return model, profile, certificate.maximum_regret <= epsilon
