"""QF_NRA encoding for discounted stationary equilibria of finite stochastic games."""

from __future__ import annotations

from collections.abc import Iterable, Sequence
from itertools import product

from .rational import Q
from .smt import ParsedModel, parse_solver_model
from .stochastic import StationaryProfile, StochasticGame


def _q(value: Q) -> str:
    if value.denominator == 1:
        return str(value.numerator)
    return f"(/ {value.numerator} {value.denominator})"


def _sum(terms: Iterable[str]) -> str:
    values = tuple(terms)
    if not values:
        return "0"
    if len(values) == 1:
        return values[0]
    return f"(+ {' '.join(values)})"


def _mul(terms: Iterable[str]) -> str:
    values = tuple(terms)
    if not values:
        return "1"
    if len(values) == 1:
        return values[0]
    return f"(* {' '.join(values)})"


def _joint_probability(variables: Sequence[Sequence[str]], joint: Sequence[int]) -> str:
    return _mul(variables[player][action] for player, action in enumerate(joint))


def _value_system(
    game: StochasticGame,
    variables: Sequence[Sequence[Sequence[str]]],
    player: int,
    beta: Q,
    prefix: str,
) -> tuple[list[str], list[str]]:
    names = [f"{prefix}_{state}" for state in range(game.states)]
    joints = tuple(product(*(range(count) for count in game.action_counts)))
    equations: list[str] = []
    for state in range(game.states):
        probabilities = {joint: _joint_probability(variables[state], joint) for joint in joints}
        reward = _sum(
            f"(* {probabilities[joint]} {_q(game.payoffs[state, joint][player])})"
            for joint in joints
            if game.payoffs[state, joint][player] != 0
        )
        continuation_terms: list[str] = []
        for target in range(game.states):
            transition_probability = _sum(
                f"(* {probabilities[joint]} {_q(game.transitions[state, joint][target])})"
                for joint in joints
                if game.transitions[state, joint][target] != 0
            )
            continuation_terms.append(f"(* {transition_probability} {names[target]})")
        continuation = _sum(continuation_terms)
        equations.append(
            f"(= {names[state]} (+ (* {_q(1 - beta)} {reward}) (* {_q(beta)} {continuation})))"
        )
    return names, equations


def export_discounted_stationary_qfnra(game: StochasticGame, beta: Q, epsilon: Q) -> str:
    """Encode independent stationary profiles and deterministic stationary deviations."""

    if not 0 <= beta < 1:
        raise ValueError("beta must lie in [0,1)")
    if epsilon < 0:
        raise ValueError("epsilon must be non-negative")
    lines = [
        "; generated by uniform-lab",
        "; SCOPE: independent stationary profiles; all unilateral discounted deviations",
        "; best-response witnesses are deterministic stationary policies of the induced MDP",
        "; UNSAT excludes only the independent stationary profile class",
        "(set-logic QF_NRA)",
        "(set-option :produce-models true)",
    ]
    variables: list[list[list[str]]] = []
    for state in range(game.states):
        state_variables: list[list[str]] = []
        for player, action_count in enumerate(game.action_counts):
            action_variables = [f"x_{state}_{player}_{action}" for action in range(action_count)]
            state_variables.append(action_variables)
            for name in action_variables:
                lines.append(f"(declare-fun {name} () Real)")
                lines.append(f"(assert (and (<= 0 {name}) (<= {name} 1)))")
            lines.append(f"(assert (= {_sum(action_variables)} 1))")
        variables.append(state_variables)

    profile_values: list[list[str]] = []
    for player in range(game.players):
        names, equations = _value_system(game, variables, player, beta, f"v_{player}")
        profile_values.append(names)
        lines.extend(f"(declare-fun {name} () Real)" for name in names)
        lines.extend(f"(assert {equation})" for equation in equations)

    for player, action_count in enumerate(game.action_counts):
        for policy_number, policy in enumerate(product(range(action_count), repeat=game.states)):
            deviating = [
                [list(actions) for actions in state_variables] for state_variables in variables
            ]
            for state, selected in enumerate(policy):
                deviating[state][player] = [
                    "1" if action == selected else "0" for action in range(action_count)
                ]
            names, equations = _value_system(
                game, deviating, player, beta, f"d_{player}_{policy_number}"
            )
            lines.extend(f"(declare-fun {name} () Real)" for name in names)
            lines.extend(f"(assert {equation})" for equation in equations)
            lines.extend(
                f"(assert (<= {name} (+ {profile_values[player][state]} {_q(epsilon)})))"
                for state, name in enumerate(names)
            )
    lines.extend(["(check-sat)", "(get-model)"])
    return "\n".join(lines) + "\n"


def stationary_profile_from_model(game: StochasticGame, model: ParsedModel) -> StationaryProfile:
    profile: list[tuple[tuple[Q, ...], ...]] = []
    for state in range(game.states):
        state_profile: list[tuple[Q, ...]] = []
        for player, action_count in enumerate(game.action_counts):
            probabilities: list[Q] = []
            for action in range(action_count):
                name = f"x_{state}_{player}_{action}"
                if name not in model.rationals:
                    raise ValueError(f"model has no independently rational value for {name}")
                probabilities.append(model.rationals[name])
            state_profile.append(tuple(probabilities))
        profile.append(tuple(state_profile))
    result = tuple(profile)
    game.validate_profile(result)
    return result


def independently_check_stochastic_model(
    game: StochasticGame, beta: Q, epsilon: Q, model_text: str
) -> tuple[ParsedModel, StationaryProfile, bool]:
    model = parse_solver_model(model_text)
    if model.status != "sat":
        raise ValueError(f"solver status is {model.status!r}, not 'sat'")
    profile = stationary_profile_from_model(game, model)
    regrets = game.discounted_stationary_regret(profile, beta)
    return model, profile, all(value <= epsilon for row in regrets for value in row)
